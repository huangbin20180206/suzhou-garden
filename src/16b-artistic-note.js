//   · 马厩里的那几匹马（同上，Rodin 生成件，品种名是资产库给的，不是考据）
// 这些**都留着**——它们是场景的生气。问题不在"有"，在"没说"：
// 懂行的访客会问"鹦鹉哪来的"，而我们没有任何地方回答。
//
// ── 做法：一条文案，两处呈现 ──────────────────────────────────────────────
//   ① `?notes=1` 时在**导览字幕**上逐站补一行「写意处理：……」（首次访问不打扰）；
//   ② 本表同时是可读的**出处文档** —— 想知道"为什么留鹦鹉"直接读这里，不用翻 git。
//
// ── 边界（如实声明）──────────────────────────────────────────────────────
//   · 本表**不改任何场景内容**，纯文案。删掉本文件页面照常跑（导览只是少一行注）。
//   · 品种名（卡马格/蒙古/克里奥罗）是**资产库给的标签**，没人核对过这些模型
//     到底像不像那三个品种 —— 文案里因此不把它们当考据陈述，只说"资产的原始标签"。
//   · 「拙政园」是真实园林；本场景是**写意再现**，不是测绘复原。这一条写在提示里。

