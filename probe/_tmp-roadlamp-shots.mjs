// _tmp-roadlamp-shots.mjs —— 【临时·只读】路灯真光源验收：昼夜 + 摇曳差分。
import http from 'node:http';
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { launchChromium, listenEphemeral } from './_harness.mjs';
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'outputs', '_diag');
const loadPlaywright = () => { const r = createRequire(import.meta.url); try { return r('playwright'); } catch {} throw new Error('no playwright'); };
const MIME = { '.html':'text/html; charset=utf-8', '.js':'text/javascript', '.glb':'model/gltf-binary', '.png':'image/png', '.json':'application/json', '.svg':'image/svg+xml', '.webmanifest':'application/manifest+json', '.mp3':'audio/mpeg' };
const srv = http.createServer((q,r)=>{ let p=decodeURIComponent(q.url.split('?')[0]); if(p==='/')p='/index.html';
  fs.readFile(path.join(ROOT,p),(e,d)=>{ if(e){r.writeHead(404);r.end();return;} r.writeHead(200,{'Content-Type':MIME[path.extname(p).toLowerCase()]||'application/octet-stream'}); r.end(d); }); });
const sleep = ms => new Promise(r=>setTimeout(r,ms));
(async () => {
  fs.mkdirSync(OUT, { recursive: true });
  const port = await listenEphemeral(srv);
  const { chromium } = loadPlaywright();
  const browser = await launchChromium(chromium);
  const page = await browser.newPage({ viewport: { width: 1180, height: 820 } });
  const errs = [];
  page.on('pageerror', e => errs.push(String(e && e.message || e)));
  page.on('console', m => { const t = m.text(); if (t.includes('真光源') || t.includes('路旁')) console.log('  [page] ' + t); });
  page.setDefaultTimeout(600000);
  await page.goto('http://127.0.0.1:' + port + '/index.html', { waitUntil: 'load', timeout: 120000 });
  await page.waitForFunction(() => window.__garden && window.__garden.bootDone && window.__garden.bootDone(), null, { timeout: 600000, polling: 300 });
  const frame = { t: [38.2, 0.60, 13.0], d: [0.55, 0.22, -0.80], dist: 8.5 };
  const setFrame = () => page.evaluate((s) => {
    const g = window.__garden, T = g.THREE;
    const t = new T.Vector3(...s.t), d = new T.Vector3(...s.d).normalize();
    g.controls.enabled = false; g.controls.enableDamping = false;
    g.camera.position.copy(t).addScaledVector(d, s.dist);
    g.camera.fov = 46; g.camera.near = 0.05; g.camera.updateProjectionMatrix();
    g.controls.target.copy(t); g.camera.lookAt(t);
  }, frame);
  await page.evaluate(() => { const g = window.__garden; try { g.guideStop(); } catch {} g.setEnv('season','summer'); g.setEnv('weather','clear'); g.setEnv('time','night'); });
  await page.waitForFunction(() => window.__garden.ENV.t >= 1, null, { timeout: 200000, polling: 200 });
  await sleep(1500);
  await setFrame(); await sleep(900);
  await page.screenshot({ path: path.join(OUT, 'roadlamp-night-a.png') }); console.log('  ✓ roadlamp-night-a.png');
  const ia = await page.evaluate(() => { const o = []; window.__garden.scene.traverse(n => { if (n.name === 'roadLamp') o.push(+n.intensity.toFixed(3)); }); return o; });
  await sleep(2500);
  await page.screenshot({ path: path.join(OUT, 'roadlamp-night-b.png') }); console.log('  ✓ roadlamp-night-b.png');
  const ib = await page.evaluate(() => { const o = []; window.__garden.scene.traverse(n => { if (n.name === 'roadLamp') o.push(+n.intensity.toFixed(3)); }); return o; });
  console.log('  INT_A=' + JSON.stringify(ia));
  console.log('  INT_B=' + JSON.stringify(ib));
  await page.evaluate(() => { window.__garden.setEnv('time','noon'); });
  await page.waitForFunction(() => window.__garden.ENV.t >= 1, null, { timeout: 200000, polling: 200 });
  await sleep(1200);
  await setFrame(); await sleep(900);
  await page.screenshot({ path: path.join(OUT, 'roadlamp-noon.png') }); console.log('  ✓ roadlamp-noon.png');
  const ino = await page.evaluate(() => { const o = []; window.__garden.scene.traverse(n => { if (n.name === 'roadLamp') o.push(+n.intensity.toFixed(3)); }); return o; });
  console.log('  INT_NOON=' + JSON.stringify(ino));
  console.log('  pageerror: ' + errs.length + (errs.length ? ' :: ' + errs.slice(0,2).join(' | ') : ''));
  await browser.close(); srv.close(); process.exit(0);
})();
